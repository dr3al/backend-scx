"""Демо 02. Вызов async-функции НЕ выполняет её тело.

Запуск:  python 02_coroutine_basics.py
"""
import asyncio


async def make_coffee() -> str:
    print("Начинаю варить кофе")
    await asyncio.sleep(2)  # точка приостановки: «пока ждём, можно делать другое»
    print("Кофе готов!")
    return "чашка кофе"


# 1. Вызов создаёт объект-корутину. Строка «Начинаю варить кофе» НЕ печатается.
coro = make_coffee()
print("Что вернул вызов:", coro)
print("Тип:", type(coro))
print("Кофе ещё не варится — тело функции не выполнялось.\n")

# 2. Выполнить корутину может только цикл событий. asyncio.run создаёт его,
#    выполняет корутину до конца и возвращает её результат.
result = asyncio.run(coro)
print("Результат:", result)
